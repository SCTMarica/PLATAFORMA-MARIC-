def normalize_language(language_code):
    if language_code in SUPPORTED_LANGUAGES:
        return language_code
    return DEFAULT_LANGUAGE


def get_language_from_request(request):
    if request is None:
        return DEFAULT_LANGUAGE
    return normalize_language(request.session.get(LANGUAGE_SESSION_KEY, DEFAULT_LANGUAGE))


def translate(key, language_code=None):
    language_code = normalize_language(language_code or DEFAULT_LANGUAGE)
    return (
        TRANSLATIONS.get(language_code, {}).get(key)
        or TRANSLATIONS[DEFAULT_LANGUAGE].get(key)
        or key
    )
